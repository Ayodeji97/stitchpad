package com.danzucker.stitchpad.core.sharing

/**
 * Every piece of fixed copy printed on a shared receipt / invoice, pre-localized
 * by the caller (see `resolveReceiptLabels()`), so [ReceiptFormatter] and the
 * native renderers stay resource-free and unit-testable.
 *
 * Defaults are the English strings the receipt has always printed — tests and
 * any caller that does not localize get byte-identical output.
 *
 * `*Template` fields are raw positional templates ("%1$s each") filled with
 * [fillTemplate] through the helper functions below.
 */
data class ReceiptLabels(
    // Document type header
    val documentInvoice: String = "INVOICE",
    val documentDepositReceipt: String = "DEPOSIT RECEIPT",
    val documentReceipt: String = "RECEIPT",
    // Priority badge
    val priorityUrgent: String = "URGENT",
    val priorityRush: String = "RUSH",
    // Payment rows
    val paymentDeposit: String = "Deposit",
    val paymentProgress: String = "Progress",
    val paymentFinal: String = "Final",
    val methodCash: String = "Cash",
    val methodTransfer: String = "Transfer",
    val methodPos: String = "POS",
    val methodOther: String = "Other",
    // Order status
    val statusPending: String = "Pending",
    val statusInProgress: String = "In Progress",
    val statusReady: String = "Ready",
    val statusDelivered: String = "Delivered",
    // Renderer section labels
    val customer: String = "CUSTOMER",
    val date: String = "DATE",
    val items: String = "ITEMS",
    val subtotal: String = "Subtotal",
    val discount: String = "Discount",
    val depositPaid: String = "Deposit Paid",
    val total: String = "Total",
    val balance: String = "Balance",
    val payViaTransfer: String = "PAY VIA TRANSFER",
    val bank: String = "Bank",
    val accountName: String = "Account name",
    val accountNumber: String = "Account number",
    val status: String = "STATUS",
    val deadline: String = "DEADLINE",
    val paidInFull: String = "✓ PAID IN FULL",
    val amountDueTemplate: String = "%1\$s DUE",
    val unitPriceEachTemplate: String = "%1\$s each",
    val orderNumberTemplate: String = "Order #%1\$s",
    // Tier-keyed footer attribution
    val footerFull: String = "Generated by StitchPad · stitchpad.app",
    val footerCompact: String = "Generated by StitchPad",
) {
    /** "₦40,000 DUE" */
    fun amountDue(formattedAmount: String): String = fillTemplate(amountDueTemplate, formattedAmount)

    /** "₦15,000 each" */
    fun unitPriceEach(formattedUnitPrice: String): String = fillTemplate(unitPriceEachTemplate, formattedUnitPrice)

    /** "Order #ORD-AB12" */
    fun orderNumber(orderIdShort: String): String = fillTemplate(orderNumberTemplate, orderIdShort)

    /** Footer line for the attribution variant; null for the Atelier white-label case. */
    fun footerFor(attribution: ReceiptAttribution): String? = when (attribution) {
        ReceiptAttribution.Full -> footerFull
        ReceiptAttribution.Compact -> footerCompact
        ReceiptAttribution.None -> null
    }
}
